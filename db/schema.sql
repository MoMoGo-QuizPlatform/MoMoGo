ALTER TABLE "TBL_PROBLEM_COUNTERS" ADD CONSTRAINT "FK_TBL_PROBLEM_TO_TBL_PROBLEM_COUNTERS" FOREIGN KEY ("problem_id") REFERENCES "TBL_PROBLEM" ("id") ON DELETE CASCADE;
